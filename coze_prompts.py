def get_prompt(book_type: str, book_name: str, book_info: str = "") -> str:
    """
    根据图书赛道组装完整口播提示词
    返回完整的 Coze 大模型节点 system prompt
    """
    config = PROMPTS.get(book_type, PROMPTS["综合"])

    prompt = f"""# 角色设定
{config['role']}

# 任务
请为图书《{book_name}》创作一条短视频口播文案。

## 图书信息
- 书名：{book_name}
- 赛道：{book_type}
- 简介：{book_info}

## 风格要求
{config['style']}

## 语气基调
{config['tone']}

## 目标受众
{config['target_audience']}

## 创作要求
"""
    for i, req in enumerate(config["requirements"], 1):
        prompt += f"{i}. {req}\n"

    prompt += f"""
## 参考开头（可参考但不必照搬）
"""
    for hook in config["hook_templates"]:
        prompt += f"- {hook}\n"

    prompt += f"""
## 结尾引导
{config['cta']}

## 输出格式
请直接输出口播文案正文，不要加"以下是文案"等引导语。
文案需要可以直接朗读，包含开头吸引、中间展示、结尾引导三段式结构。
"""

    return prompt


def get_all_categories() -> list:
    """获取全部赛道列表"""
    return list(PROMPTS.keys())


def get_hook(book_type: str, book_name: str) -> str:
    """获取单个开头模板（用于快速预览）"""
    config = PROMPTS.get(book_type, PROMPTS["综合"])
    return config["hook_templates"][0].replace("{book_name}", book_name)


